"""Build the whole corpus into a directory: files, corrupt zip and README."""

import io
from pathlib import Path

from corpus_gen.documents import (
    CORPUS,
    CORRUPT_DESCRIPTION,
    CORRUPT_NAME,
    CORRUPT_SOURCE,
    CorpusFile,
)
from corpus_gen.package import finalize

README = "README.md"
HAND_WRITTEN_MARKER = "<!-- Hand-written below this line: kept by `just corpus`. -->"
"""Lines after the marker (e.g. Word-saved variants, T-005c) survive regeneration."""

README_HEADER = """\
# Test corpus

Generated by `just corpus` (`corpus/generator/`, T-005a, ADR-031, ADR-041). Do not edit the
files or the list below by hand; change the generator and regenerate. The output is
byte-identical from one run to the next.

| File | What it stresses |
|---|---|
"""

DEFAULT_HAND_WRITTEN = """
## Word-saved variants (T-005c)

None yet.
"""


def build_file(entry: CorpusFile) -> bytes:
    """Return the final bytes of one corpus file."""
    raw = io.BytesIO()
    entry.build().save(raw)
    return finalize(raw.getvalue(), seed=entry.name, word_ids=entry.word_ids)


def corrupt(valid: bytes) -> bytes:
    """Return ``valid`` truncated to half: the zip central directory is lost."""
    return valid[: len(valid) // 2]


def readme(previous: str | None) -> str:
    """Return the README text, keeping the hand-written part of ``previous``."""
    rows = [f"| `{entry.name}` | {entry.description} |" for entry in CORPUS]
    rows.append(f"| `{CORRUPT_NAME}` | {CORRUPT_DESCRIPTION} |")
    hand_written = DEFAULT_HAND_WRITTEN
    if previous is not None and HAND_WRITTEN_MARKER in previous:
        hand_written = previous.split(HAND_WRITTEN_MARKER, 1)[1]
    return README_HEADER + "\n".join(rows) + "\n\n" + HAND_WRITTEN_MARKER + hand_written


def build_corpus(out_dir: Path) -> list[Path]:
    """Write every corpus file and the README into ``out_dir``; return the written paths."""
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    built: dict[str, bytes] = {}
    for entry in CORPUS:
        built[entry.name] = build_file(entry)
        path = out_dir / entry.name
        path.write_bytes(built[entry.name])
        written.append(path)
    corrupt_path = out_dir / CORRUPT_NAME
    corrupt_path.write_bytes(corrupt(built[CORRUPT_SOURCE]))
    written.append(corrupt_path)
    readme_path = out_dir / README
    previous = readme_path.read_text(encoding="utf-8") if readme_path.exists() else None
    readme_path.write_text(readme(previous), encoding="utf-8", newline="\n")
    written.append(readme_path)
    return written
